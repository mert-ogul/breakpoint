def int4_note(data: ReportData) -> str | None:
    """One limitations line when the lock records INT4; None for packages without INT4 fields."""
    art = data.lock["artifacts"]
    if "int4_status" not in art:
        return None
    status = art["int4_status"]
    ran = any(r["condition_id"] == "precision_int4_weight_only" for r in data.rows)
    if status == "ok" and ran:
        if EXPORT_VALIDATION_INT4_NAME not in data.validation_files:
            raise ReportDataError(
                f"INT4 ran but {EXPORT_VALIDATION_INT4_NAME} is missing from validation_files"
            )
        sidecar = data.validation_files[EXPORT_VALIDATION_INT4_NAME]
        try:
            coverage = sidecar["quantization_coverage"]
            runtime = sidecar["runtime_checks"]
            recipe = coverage["recipe"]
            nbits = coverage["matmul_nbits_nodes"]
            total = coverage["matmul_nodes_total"]
            fraction = coverage["weight_params_int4_fraction"]
            accuracy_level = recipe["accuracy_level"]
            max_abs = runtime["max_abs_error"]
            mean_abs = runtime["mean_abs_error"]
        except KeyError as exc:
            raise ReportDataError(f"INT4 sidecar missing required key {exc.args[0]!r}") from exc
        return (
            f"INT4 weight-only: {nbits} of {total} MatMul nodes as 4-bit "
            f"({fraction:.1%} of weights, accuracy_level={accuracy_level}); "
            f"max abs error {format_sig(float(max_abs))}, mean abs {format_sig(float(mean_abs))}. "
            "Not a full-model INT4 result; no INT4 device timing."
        )
    detail = art.get("int4_detail")
    detail_bit = f" ({detail})" if detail else ""
    return (
        f"INT4 export status is '{status}'{detail_bit}; no INT4 condition was run and no INT4 "
        "measurement is reported."
    )


def _h264_unsupported_record(data: ReportData) -> dict[str, Any] | None:
    path = data.data_dir / "protocol" / "h264_unsupported.json"
    if not path.is_file():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ReportDataError(f"malformed protocol/h264_unsupported.json: {exc}") from exc
    if not isinstance(payload, dict):
        raise ReportDataError("protocol/h264_unsupported.json must be a JSON object")
    return payload


def h264_note(data: ReportData) -> str | None:
    """Limitations line for a run H.264 plan or an explicit unsupported record."""
    h264_axis = next((a for a in data.axes if a.axis == "h264"), None)
    unsupported = _h264_unsupported_record(data)
    if h264_axis is None and unsupported is None:
        return None
    if h264_axis is None:
        status = unsupported.get("status") if unsupported else "unsupported"
        detail = unsupported.get("detail") if unsupported else None
        detail_bit = f" ({detail})" if detail else ""
        return (
            f"H.264 was not run: status is '{status}'{detail_bit}; no H.264 bitrate conditions "
            "are reported."
        )
    overshoots: list[float] = []
    for view in h264_axis.conditions:
        for row in view.rows:
            req = row.get("h264_requested_kbps")
            actual = row.get("h264_actual_kbps")
            if req is None or actual is None:
                continue
            overshoots.append(float(actual) - float(req))
    largest = max(overshoots) if overshoots else 0.0
    locked = data.lock.get("h264") or {}
    pyav = locked.get("pyav_version")
    libav = locked.get("libav_versions") or {}
    libavcodec = libav.get("libavcodec") or libav.get("avcodec")
    preset = locked.get("preset")
    gop = locked.get("gop")
    tune = locked.get("tune")
    return (
        "H.264: same-step encode/decode, visual quality only, ABR "
        f"(largest overshoot {largest:+.1f} kbps). "
        f"PyAV {pyav}, libavcodec {format_libav_version(libavcodec)}, "
        f"preset={preset}, gop={gop}, tune={tune}."
    )


def report_limitations(data: ReportData) -> list[str]:
    n = len(data.rows)
    outcomes: dict[str, int] = {}
    for row in data.rows:
        outcomes[row["outcome"]] = outcomes.get(row["outcome"], 0) + 1
    errors = outcomes.get("runtime_error", 0) + outcomes.get("policy_failed", 0)
    first = data.axes[0]
    int8 = data.lock["artifacts"]["int8_status"]
    notes = [
        f"Errors: {errors} runtime errors or policy failures in {n} episode records. Outcomes: "
        + ", ".join(f"{v} {k}" for k, v in sorted(outcomes.items()))
        + ".",
        int8_note(data, int8),
    ]
    int4_line = int4_note(data)
    if int4_line is not None:
        notes.append(int4_line)
    h264_line = h264_note(data)
    if h264_line is not None:
        notes.append(h264_line)
    base = baseline_view(first)
    relation = "above" if first.baseline_rate >= first.baseline_floor else "below"
    notes += [
        f"Baseline {base.successes}/{base.eligible} ({pct(first.baseline_rate)}), "
        f"{relation} the {first.baseline_floor:g} floor.",
        f"Sample size: {episodes_per_condition(data)} paired episodes per condition. "
        "A grid point below the threshold is not an interpolated exact boundary.",
    ]
    unresolved = [
        f"{a.title}: {', '.join(plain_label(v.condition_id) for v in unresolved_conditions(a))}"
        for a in data.axes
        if unresolved_conditions(a)
    ]
    notes.append(
        '"Interval spans threshold" means the Wilson interval overlaps the threshold; that is '
        "an interval overlap, not a paired significance test. Conditions: "
        + ("; ".join(unresolved) if unresolved else "none")
        + "."
    )
    suppressed = [f"{a.title}: {a.suppressed_reason}" for a in data.axes if a.suppressed_reason]
    if suppressed:
        notes.append("Threshold comparisons not reported: " + "; ".join(suppressed) + ".")
    resolution = next(a for a in data.axes if a.axis == "resolution")
    if len({v.ordered_value for v in resolution.conditions[1:]}) == 1:
        notes.append(
            "Resolution ordering: the saved summary stored the same ordered value for "
            "every resolution, so conditions are ordered by plan order (native, "
            "240x320, 120x160, 60x80), which is mild to severe."
        )
    rpi = next(p for p in data.profiles if p.device == "rpi5")
    notes.append(
        f"Pi 5 timings were captured while throttling was reported in "
        f"{rpi.telemetry['throttled_now']} of {rpi.telemetry['n_samples']} telemetry samples; "
        "cooling and power were not recorded."
    )
    return notes


def observations(data: ReportData) -> list[str]:
    base = baseline_view(data.axes[0])
    lines = [
        f"Baseline (ONNX FP32, native image, 0 ms delay): {base.successes}/{base.eligible} "
        f"({pct(base.successes / base.eligible)}; Wilson 95% {wilson_text(base)})."
    ]
    for axis in data.axes:
        if axis.suppressed_reason:
            lines.append(
                f"{axis.title}: threshold comparison not reported ({axis.suppressed_reason})."
            )
        elif axis.ordered:
            below = [v for v in axis.conditions if v.below_threshold]
            if below:
                first = below[0]
                tag = " (interval includes threshold)" if first.threshold_inside_interval else ""
                lines.append(
                    f"{axis.title}: first tested point below threshold is "
                    f"{plain_label(first.condition_id)} at "
                    f"{first.successes}/{first.eligible}{tag}."
                )
            else:
                lines.append(f"{axis.title}: no tested point is below the threshold.")
        else:
            verdicts = [
                f"{plain_label(v.condition_id)} {v.successes}/{v.eligible} "
                f"{'below' if v.below_threshold else 'not below'}"
                for v in axis.conditions
                if not v.is_baseline
            ]
            lines.append(
                f"{axis.title} (categorical comparison, no ordering) against "
                f"{axis.ratio:g} x baseline: {'; '.join(verdicts)}."
            )
    return lines


def working_tree_porcelain_note(status_porcelain: Any) -> str:
    """HTML for the code-revision parenthetical from git status --porcelain."""
    text = "" if status_porcelain is None else str(status_porcelain)
    lines = [line.rstrip("\n") for line in text.splitlines() if line.strip()]
    if not lines:
        return "clean"
    return ", ".join(f"<code>{esc(line)}</code>" for line in lines)



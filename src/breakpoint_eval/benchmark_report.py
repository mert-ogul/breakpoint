def write_data_index(data: ReportData, out_dir: Path, written: list[Path]) -> Path:
    files = [
        {
            "path": p.relative_to(out_dir).as_posix(),
            "bytes": p.stat().st_size,
            "sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
        }
        for p in sorted(written)
    ]
    payload = {
        "schema_version": 1,
        "generator": "scripts/render_benchmark.py",
        "breakpoint_eval_version": __version__,
        "input": {
            "manifest_sha256": data.manifest_sha256,
            "episode_rows": len(data.rows),
            "simulated_runs": data.n_runs,
        },
        "validation": [
            {"name": c.name, "passed": c.passed, "detail": c.detail} for c in data.checks
        ],
        "displayed_counts": displayed_counts(data),
        "derived_by_report": [
            "device_profile axis counts and paired tables",
            "threshold-inside-interval flags",
            "timing statistics",
            "Pi telemetry summary",
        ],
        "files": files,
    }
    path = out_dir / "data_index.json"
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def load_validated_data(input_dir: Path) -> ReportData:
    """Load the packaged data and refuse to continue if any integrity check fails."""
    data = load_report_data(input_dir)
    failed = [c for c in data.checks if not c.passed]
    if failed:
        raise ReportValidationError("; ".join(f"{c.name}: {c.detail}" for c in failed))
    return data


def results_markdown(data: ReportData) -> str:
    """Compact results table and headline observations, in the form embedded in the README."""
    n = episodes_per_condition(data)
    lines = [
        f"| Stress | Conditions and successes (of {n}) |",
        "| --- | --- |",
    ]
    for axis in data.axes:
        cells = [
            f"{plain_label(v.condition_id)}: {v.successes}"
            for v in axis.conditions
            if not (axis.axis == "device_profile" and v.condition_id == axis.baseline_condition_id)
        ]
        lines.append(f"| {axis.title} | {', '.join(cells)} |")
    return "\n".join([*lines, "", *[f"- {line}" for line in observations(data)]])


def update_readme_results(input_dir: Path, readme: Path) -> bool:
    """Rewrite the generated block of ``readme``; return True if the file changed."""
    text = readme.read_text(encoding="utf-8")
    start, end = text.find(README_RESULTS_START), text.find(README_RESULTS_END)
    if start < 0 or end < start:
        raise ReportValidationError(f"{readme} lacks the generated results markers")
    block = results_markdown(load_validated_data(input_dir))
    updated = f"{text[: start + len(README_RESULTS_START)]}\n{block}\n{text[end:]}"
    if updated != text:
        readme.write_text(updated, encoding="utf-8")
    return updated != text


def render_benchmark_report(input_dir: Path, out_dir: Path) -> list[Path]:
    """Validate the packaged data, then write plots, index.html, report.md and data_index.json."""
    data = load_validated_data(input_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    plots_dir = out_dir / "plots"
    render_all_plots(data.axes, data.profiles, plots_dir)
    written = sorted(plots_dir.glob("*"))
    html_path = out_dir / "index.html"
    md_path = out_dir / "report.md"
    html_path.write_text(render_html(data, out_dir, "plots"), encoding="utf-8")
    md_path.write_text(render_markdown(data, out_dir, "plots"), encoding="utf-8")
    written += [html_path, md_path]
    written.append(write_data_index(data, out_dir, written))
    LOGGER.info("wrote %d files to %s", len(written), out_dir)
    return written
